#!/usr/bin/env python3
"""Generate the `semantic_lab` world = flat_lab + one instance of every detector class (+ ground-truth list).

    python3 vision/make_test_world.py            # writes worlds/semantic_lab.sdf, worlds/meshes/*.obj, docs/results/data/phase4/semantic_lab_gt.json
    python3 vision/make_test_world.py --check    # exit 1 if the committed files are out of date

The three coloured boxes of flat_lab count as class `box` (red/blue/yellow); `table` and `green_cylinder` stay
unlabelled distractors. Objects have simple box collisions so Nav2/the lidar treat them as obstacles.
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "gurdy_core"))
from vision import objects as O  # noqa: E402

WORLDS = ROOT / "ros2_ws/src/gurdy_gazebo/worlds"
GT_JSON = ROOT / "docs/results/data/phase4/semantic_lab_gt.json"

# (name, class, x, y, yaw, variant)
PLACED = [
    ("barrel_a", "barrel", -1.0, -1.6, 0.0, {"rgb": [0.10, 0.30, 0.85]}),
    ("extinguisher", "fire_extinguisher", -1.2, 1.9, 0.0, {}),
    ("cone", "traffic_cone", 1.8, -0.7, 0.0, {}),
    ("toolbox", "toolbox", -1.5, 0.5, 0.6, {"rgb": [0.85, 0.12, 0.10]}),
    ("mannequin", "mannequin", 3.8, 0.4, 2.8, {"skin": [0.93, 0.80, 0.68], "rgb": [0.2, 0.3, 0.7], "rgb2": [0.3, 0.3, 0.3]}),
    ("chair", "chair", 5.5, 2.0, 0.9, {"rgb": [0.35, 0.22, 0.10]}),
    ("barrel_b", "barrel", 5.6, -2.2, 0.0, {"rgb": [0.85, 0.12, 0.10]}),
    ("cardboard_box", "box", 3.6, -2.4, 0.3, {"plain": False, "rgb": list(O.CARDBOARD), "dims": [0.40, 0.35, 0.30]}),
]
FLAT_LAB_BOXES = [("red_box", 1.0, 1.6, "red"), ("blue_box", 1.8, -2.2, "blue"), ("yellow_box", 4.6, -1.5, "yellow")]


def build():
    base = (WORLDS / "flat_lab.sdf").read_text()
    (WORLDS / "meshes").mkdir(exist_ok=True)
    models, gt = [], []
    for name, cls, x, y, yaw, var in PLACED:
        models.append(O.model_sdf(name, O.parts(cls, 1.0, var), x, y, yaw, collision=True, mesh_dir=str(WORLDS / "meshes"),
                                  mesh_rel="meshes"))
        gt.append({"name": name, "class": cls, "x": x, "y": y, "color": ""})
    for name, x, y, color in FLAT_LAB_BOXES:
        gt.append({"name": name, "class": "box", "x": x, "y": y, "color": color})
    text = base.replace("<world name=\"flat_lab\">", "<world name=\"semantic_lab\">").replace(
        "GENERATED by scripts/gen_world_flat_lab.py - edit the script, not this file.",
        "GENERATED by vision/make_test_world.py from flat_lab.sdf - edit the script, not this file.")
    text = text.replace("  </world>", "    <!-- detector test objects (Phase 4) -->\n" + "".join(models) + "  </world>")
    return text, json.dumps({"objects": gt}, indent=1) + "\n"


def targets():
    return WORLDS / "semantic_lab.sdf", GT_JSON


if __name__ == "__main__":
    sdf, gt = build()
    if "--check" in sys.argv:
        ok = targets()[0].exists() and targets()[0].read_text() == sdf and targets()[1].exists() and targets()[1].read_text() == gt
        sys.exit(0 if ok else 1)
    targets()[1].parent.mkdir(parents=True, exist_ok=True)
    targets()[0].write_text(sdf)
    targets()[1].write_text(gt)
    print(f"wrote {targets()[0]} ({len(sdf)} bytes) and {targets()[1]}")
