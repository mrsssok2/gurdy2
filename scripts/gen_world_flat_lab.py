#!/usr/bin/env python3
"""Generate ros2_ws/src/gurdy_gazebo/worlds/flat_lab.sdf (small two-room lab for mapping/Nav2).

    python3 scripts/gen_world_flat_lab.py            # rewrite the SDF
    python3 scripts/gen_world_flat_lab.py --check    # exit 1 if the committed SDF is out of date

Layout (metres, robot spawns at the origin facing +x, in room A):

    y=+3 +------------------------+------------------------------+
         |  room A                |  room B                      |
         |            [table]     |        (green cyl)           |
         |  [red]                 |                              |
    y=0  |  R->                   |                              |   doorway: x = 2.5, y in [0.0, 1.0]
         |                  doorway gap                          |
         |        [blue]          |        [blue box]            |
    y=-3 +------------------------+------------------------------+
        x=-2                     x=2.5                          x=6.5

Only static boxes/cylinders, flat colours, no textures, no shadows: cheap on RAM and rendering.
Everything is taller than the lidar plane (~0.16 m above ground). The doorway is wide enough for
the robot footprint plus inflation (checked in gurdy_navigation/test).
"""
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "ros2_ws/src/gurdy_gazebo/worlds/flat_lab.sdf"

WALL_T = 0.10
WALL_H = 1.0
X_MIN, X_MAX, Y_MIN, Y_MAX = -2.0, 6.5, -3.0, 3.0
DIVIDER_X = 2.5
DOOR_Y = (0.0, 1.0)             # doorway gap in the divider wall (y_low, y_high)

# (name, kind, (x, y), size, rgb). box size = (sx, sy, sz); cylinder size = (radius, height).
OBJECTS = [
    ("red_box", "box", (1.0, 1.6), (0.30, 0.30, 0.30), (0.85, 0.10, 0.10)),
    ("table", "box", (0.9, -1.4), (0.60, 0.30, 0.50), (0.45, 0.45, 0.45)),
    ("blue_box", "box", (1.8, -2.2), (0.25, 0.40, 0.30), (0.10, 0.20, 0.85)),
    ("green_cylinder", "cylinder", (4.5, 1.6), (0.15, 0.40), (0.10, 0.65, 0.20)),
    ("yellow_box", "box", (4.6, -1.5), (0.35, 0.35, 0.35), (0.90, 0.80, 0.10)),
]


def walls():
    """Static wall boxes as (name, (cx, cy), (sx, sy))."""
    w = WALL_T
    out = [
        ("wall_south", ((X_MIN + X_MAX) / 2, Y_MIN), (X_MAX - X_MIN + w, w)),
        ("wall_north", ((X_MIN + X_MAX) / 2, Y_MAX), (X_MAX - X_MIN + w, w)),
        ("wall_west", (X_MIN, (Y_MIN + Y_MAX) / 2), (w, Y_MAX - Y_MIN)),
        ("wall_east", (X_MAX, (Y_MIN + Y_MAX) / 2), (w, Y_MAX - Y_MIN)),
    ]
    lo = (Y_MIN + DOOR_Y[0]) / 2, DOOR_Y[0] - Y_MIN       # divider below the doorway
    hi = (DOOR_Y[1] + Y_MAX) / 2, Y_MAX - DOOR_Y[1]       # divider above it
    out.append(("divider_low", (DIVIDER_X, lo[0]), (w, lo[1])))
    out.append(("divider_high", (DIVIDER_X, hi[0]), (w, hi[1])))
    return out


def _static_model(name, pose_xy, z, geom, rgb):
    r, g, b = rgb
    return f"""    <model name="{name}">
      <static>true</static>
      <pose>{pose_xy[0]:.3f} {pose_xy[1]:.3f} {z:.3f} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry>{geom}</geometry></collision>
        <visual name="visual"><geometry>{geom}</geometry>
          <material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse></material></visual>
      </link>
    </model>
"""


def build() -> str:
    parts = ["""<?xml version="1.0"?>
<!-- GENERATED by scripts/gen_world_flat_lab.py - edit the script, not this file. -->
<!-- flat_lab: two rooms, one doorway, a few coloured objects (Phase 3 mapping / navigation). -->
<sdf version="1.10">
  <world name="flat_lab">
    <physics name="1ms" type="dart">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>

    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry>
          <surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry>
          <material><ambient>0.6 0.6 0.6 1</ambient><diffuse>0.7 0.7 0.7 1</diffuse></material>
        </visual>
      </link>
    </model>

"""]
    for name, xy, (sx, sy) in walls():
        geom = f"<box><size>{sx:.3f} {sy:.3f} {WALL_H}</size></box>"
        parts.append(_static_model(name, xy, WALL_H / 2, geom, (0.85, 0.85, 0.80)))
    for name, kind, xy, size, rgb in OBJECTS:
        if kind == "box":
            geom = f"<box><size>{size[0]} {size[1]} {size[2]}</size></box>"
            z = size[2] / 2
        else:
            geom = f"<cylinder><radius>{size[0]}</radius><length>{size[1]}</length></cylinder>"
            z = size[1] / 2
        parts.append(_static_model(name, xy, z, geom, rgb))
    parts.append("  </world>\n</sdf>\n")
    return "".join(parts)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(text)} bytes)")
