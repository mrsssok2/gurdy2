"""RobotBackend: one method per tool. Agent, safety checker, evaluation and data generator see only this.

Implementations: `brain.mock.MockBackend` (pure Python, virtual clock) and, in milestone 5.6, `RosBackend`.
Every method takes already-validated keyword arguments and returns a `Result`. Motion methods return
immediately with {task_id, state: "started", estimate: {distance_m, duration_s}} and report the final
result through `poll_events()` as a `task_finished` event (design section 2, conventions).
"""
from __future__ import annotations

from typing import Any, Protocol, runtime_checkable

from .specs import TOOLS
from .types import Result


@runtime_checkable
class RobotBackend(Protocol):
    # motion
    def walk(self, direction: str, distance_m: float) -> Result: ...
    def turn(self, direction: str, angle_deg: float) -> Result: ...
    def go_to(self, place: str | None = None, object: dict | None = None, object_id: int | None = None,
              point: dict | None = None, standoff_m: float = 0.6) -> Result: ...
    def find(self, object: dict, approach: bool = False, max_time_s: float = 300) -> Result: ...
    def explore(self, max_time_s: float = 600, area: str | None = None) -> Result: ...
    def patrol(self, places: list[str], loops: int = 1) -> Result: ...
    def inspect(self, object: dict | None = None, object_id: int | None = None) -> Result: ...
    def return_home(self) -> Result: ...
    def stop(self) -> Result: ...
    def mission_control(self, action: str) -> Result: ...
    def schedule(self, delay_s: int, call: dict) -> Result: ...
    # questions
    def where_is(self, object: dict) -> Result: ...
    def whats_nearby(self, radius_m: float = 2.0) -> Result: ...
    def where_am_i(self) -> Result: ...
    def relation(self, a: dict, b: dict) -> Result: ...
    def path_check(self, place: str | None = None, object: dict | None = None, object_id: int | None = None,
                   point: dict | None = None) -> Result: ...
    def status(self) -> Result: ...
    def why(self, about: str) -> Result: ...
    def recall(self, what: str, query: dict | None = None) -> Result: ...
    def describe_view(self, question: str | None = None) -> Result: ...
    def report(self, mission_id: int | None = None) -> Result: ...
    # configuration
    def no_go_zone(self, action: str, place: str | None = None, around_object_id: int | None = None,
                   radius_m: float = 0.8) -> Result: ...
    def save_place(self, name: str) -> Result: ...
    # infrastructure (not tools)
    def now(self) -> float: ...                       # sim time, seconds
    def poll_events(self) -> list[dict[str, Any]]: ...  # events since the last call
    def known_places(self) -> list[str]: ...


def missing_methods(backend: Any) -> list[str]:
    """Tool names a backend does not implement (used by tests; runtime_checkable only checks names)."""
    return [n for n in (*(t for t in TOOLS if t != "ask_user"), "now", "poll_events", "known_places") if not callable(getattr(backend, n, None))]
